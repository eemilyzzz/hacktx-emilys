-- Run in YOUR Snowflake worksheet with a role allowed to create these objects.
-- This file contains no credentials and does not run automatically.
CREATE WAREHOUSE IF NOT EXISTS CLUBCAL_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS CLUBCAL;
CREATE SCHEMA IF NOT EXISTS CLUBCAL.APP;
CREATE ROLE IF NOT EXISTS CLUBCAL_APP;
GRANT USAGE ON WAREHOUSE CLUBCAL_WH TO ROLE CLUBCAL_APP;
GRANT USAGE ON DATABASE CLUBCAL TO ROLE CLUBCAL_APP;
GRANT USAGE ON SCHEMA CLUBCAL.APP TO ROLE CLUBCAL_APP;
GRANT CREATE TABLE ON SCHEMA CLUBCAL.APP TO ROLE CLUBCAL_APP;
-- Replace YOUR_USERNAME with your Snowflake user, then run the grant:
-- GRANT ROLE CLUBCAL_APP TO USER YOUR_USERNAME;
-- ClubCal creates its four tables after you connect with this role.
